function c = config(varargin)
%CONFIG 任务3.5曲线未知在线寻优配置：对象物理与任务7-10一致(空速=地速−风、
% 风不影响运动、实际约束动力学), 核心设定: 空速最优点u*固定且已知(曲线先验),
% 风不影响运动、实际约束动力学)。任务3.5设定: 曲线未知(控制器侧经ctrl_view剔除
% 全部曲线/最优点真值), 风也未知; 只能靠'调速度→功率'黑盒采样, 经全速度域快扫标定
% (swLo→swHi, 用户建议3→12 m/s)联合辨识曲线f与风w, 在线精化û*; RL(策略梯度)为对照。
% 继承任务7实际约束(转弯半径50-150m物理化 / 通信时延0-0.5s(任务3.5放宽下限:
% 0=无时延对照口径, 需求口径0.1-0.5) / 加速度限幅
% 2 m/s^2 / 开环固定基线)与任务8曲线标定(DJI Mavic Pro参考: 悬停103.7W、
% 谷底V*=6.3m/s、P(20)=134.5W; curveCase=谷底/悬停∈{0.95,0.90,0.85};
% 内部归一化单位, 面板按pHover换算瓦特)。
% 任务3.5新增风场参数(wind_field.m 七种模型):
%   windKind    'const'(默认,任务3.5主口径)|'sin'|'square'|'triangle'|
%               'turb'|'composite'(最贴近实际,推荐面板默认)|'sector'
%   squareEdge  方波软边陡度k(默认4; 1≈正弦, k→∞纯方波, 纯方波不物理)
%   turbStd     composite中湍流平稳标准差(默认0.3 m/s)
%   turbTheta   OU湍流速率参数(默认0.2 → 相关时间5 s)
% 速度语义(用户口径, 与对象物理一致): 空速=地速−风速(矢量), 功率由空速决定
% (空速-功率标定曲线严格固定), 地速-功率曲线随风平移(顺风右移/逆风左移),
% 仪表盘显示地速。任务3.5只用static场景(无平移调度): u*固定, Pmin恒定。
% 任务3.5新增风推断参数(windinfer_run): wiSweepMin 窗内最小航向扫角(rad),
%   wiEwma 风估计EMA平滑系数(越大越跟新)。
% 任务3.5新增纯奖励RL参数(pure_rl_run, 源自3.2): plSigma0/plSigmaMin 探索幅值起止,
%   plLr 学习率, plKern 邻域共享核宽, plHold 符号保持步数, plBins 航向桶数
%   plWarmMax 预训练(试飞时段)步数上限(3.5)
% 任务3.5新增混合主角参数(hybrid_run): hySweepMin 窗内最小航向扫角(rad, 兼容保留),
%   hyEwma 兼容保留, hyRefitEvery 低频再锚定守卫间隔(步),
%   hySseMargin 守卫曲线接受门槛(联合集相对SSE改善比例, 0.998=须改善0.2%才接受)。
% 对象侧升级不改控制器因果接口(AGENTS.md红线2): 算法仍只调 plant.q(v,tag)。
c=struct('lower',0,'upper',20,'optimum0',6.3,...
    'pHover',103.7,'p20',134.5,'curveCase',0.90,...
    'rippleA1',0.022,'rippleL1',6.0,'rippleF1',pi,...
    'rippleA2',0.012,'rippleL2',2.0,'rippleF2',pi,...
    'noiseSigma',0.01,'impulse',false,'impulseRate',0.03,'impulseSize',0.10,...
    'tEval',1.0,'duration',600,'tailSteps',60,'seed',1,...
    'eps',0.4,...
    'initialSpeed',6.3,...   % 任务7口径: 以名义巡航速度开始任务窗(爬升段不在评价窗内)
    'turnRadius',100,'latencySec',0.3,'aMax',2.0,'subSteps',10,'openLoopV',6.3,...
    'shiftTime',120,'jumpUpDx',2.7,'jumpDownDx',-2.3,'dyOffset',0.05,...
    'rampStart',60,'rampEnd',180,'rampDx',1.7,...
    'estDither',0.4,'estQa',0.05,'estRmis',0.02,'estStepClamp',0.4,...
    'wiSweepMin',0.8,'wiEwma',0.5,...
    'swLo',3.0,'swHi',12.0,'swSteps',150,'swRefitEvery',20,'swWinMax',220,...
    'ucProbeDelta',0.25,'ucProbeEvery',15,'ucGain',0.30,'ucB0',0.015,'ucThr',0.06,...
    'rlSigma',0.30,'rlSigmaMin',0.12,'rlLr',0.200,...
    'plSigma0',1.20,'plSigmaMin',0.50,'plLr',10.0,'plKern',1,'plHold',2,'plBins',12,'plWarmMax',2400,...
    'hySweepMin',0.8,'hyEwma',0.5,'hyRefitEvery',20,'hySseMargin',0.998,'hyWindEvery',10,...
    'windAmp',0.0,'windOmega',0.08,'windBias',3.5,...
    'windAmpY',0.0,'windOmegaY',0.13,'windBiasY',0.0,...
    'windDirDeg',0,...
    'windKind','const','squareEdge',4.0,'turbStd',0.3,'turbTheta',0.2,...
    'energyAccounting',true);
if ~isempty(varargin) && isstruct(varargin{1})   % 支持以struct为基底覆盖
    base=varargin{1}; fn=fieldnames(base);
    for kb=1:numel(fn), c.(fn{kb})=base.(fn{kb}); end
    varargin(1)=[];
end
assert(mod(numel(varargin),2)==0,'w35:Config','Use name/value pairs.');
for k=1:2:numel(varargin)
    key=char(varargin{k}); assert(isfield(c,key),'w35:Config','Unknown setting: %s',key);
    c.(key)=varargin{k+1};
end
assert(islogical(c.energyAccounting) && isscalar(c.energyAccounting),...
    'w35:Config','energyAccounting must be logical.');
assert(islogical(c.impulse) && isscalar(c.impulse),'w35:Config','impulse must be logical.');
positive={'tEval','duration','tailSteps','eps','initialSpeed',...
    'turnRadius','latencySec','aMax','subSteps','openLoopV',...
    'shiftTime','dyOffset','rampStart','rampEnd','rampDx',...
    'rippleA1','rippleL1','rippleA2','rippleL2','noiseSigma','impulseRate','impulseSize',...
    'seed','windAmp','windBias','windAmpY','windBiasY',...
    'estDither','estQa','estRmis','estStepClamp',...
    'wiSweepMin','wiEwma','swLo','swHi','swSteps','swRefitEvery','swWinMax',...
    'ucProbeDelta','ucProbeEvery','ucGain','ucB0','ucThr',...
    'rlSigma','rlSigmaMin','rlLr',...
    'plSigma0','plSigmaMin','plLr','plKern','plHold','plBins','plWarmMax','hyWindEvery',...
    'hySweepMin','hyEwma','hyRefitEvery','hySseMargin'};
for k=1:numel(positive), validateattributes(c.(positive{k}),{'double'},...
    {'scalar','real','finite','nonnegative'}); end
signed={'jumpUpDx','jumpDownDx','windDirDeg','windOmega','windOmegaY'};
for k=1:numel(signed), validateattributes(c.(signed{k}),{'double'},{'scalar','real','finite'}); end
assert(ischar(c.windKind) && any(strcmp(c.windKind,...
    {'const','sin','square','triangle','turb','composite','sector'})),...
    'w35:Config','windKind must be const/sin/square/triangle/turb/composite/sector.');
assert(c.squareEdge>=0.5,'w35:Config','squareEdge must be >=0.5 (1≈正弦, 越大方波越陡).');
assert(c.turbStd>=0 && c.turbTheta>0,'w35:Config','turbStd must be >=0 (0=无湍流), turbTheta>0.');
assert(any(abs(c.curveCase-[0.95 0.90 0.85])<1e-12),'w35:Config',...
    'curveCase must be 0.95 / 0.90 / 0.85.');
assert(c.lower>=0 && c.upper>c.lower && c.optimum0>=c.lower && c.optimum0<=c.upper,...
    'w35:Config','Invalid bounds/optimum.');
% ---- 三次光滑标定曲线系数(涟漪锚点补偿: P(0)=1 与 P(V*)=curveCase 精确成立) ----
rip0=c.rippleA1*cos(2*pi*(0-c.optimum0)/c.rippleL1+c.rippleF1)...
    +c.rippleA2*cos(2*pi*(0-c.optimum0)/c.rippleL2+c.rippleF2);
s0=1-rip0;
sV=c.curveCase+c.rippleA1+c.rippleA2;
s20=c.p20/c.pHover;
V=c.optimum0;
M=[0 0 0 1; V^3 V^2 V 1; 3*V^2 2*V 1 0; 20^3 20^2 20 1];
c.curveCoef=(M\[s0;sV;0;s20]).';
assert(c.initialSpeed>=c.lower && c.initialSpeed<=c.upper,'w35:Config','Initial speed outside bounds.');
assert(c.openLoopV>=c.lower && c.openLoopV<=c.upper,'w35:Config','openLoopV outside bounds.');
% ---- 任务7实际约束的有效范围 ----
assert(c.turnRadius>=30 && c.turnRadius<=600,'w35:Config',...
    'turnRadius must be in [30,600] m (研究口径50-150; 500仅作任务6旧参考).');
assert(c.latencySec>=0 && c.latencySec<=0.5,'w35:Config',...
    'latencySec must be in [0,0.5] s (0=无时延对照口径; 需求口径0.1-0.5).');
assert(c.aMax>=0.5 && c.aMax<=5,'w35:Config','aMax must be in [0.5,5] m/s^2 (需求=2).');
assert(c.subSteps>=10 && mod(c.subSteps,1)==0,'w35:Config',...
    'subSteps must be integer >=10 (0.1 s子步分辨率, 匹配最小时延).');
assert(c.duration>c.tailSteps,'w35:Config','duration too short.');
end
