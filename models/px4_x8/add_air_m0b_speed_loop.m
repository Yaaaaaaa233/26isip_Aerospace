    cfgLines = { ...
        "model: air_spare", "stage: M0-B", ...
        "speed_loop_enable: 0 (bypass; bit-exact M0-A behaviour)", ...
        "optimizer_enable: 0", ...
        "v_ref_manual_mps: 5.0", "v_ref_optimizer_mps: 5.0 (M0-C placeholder)", ...
        "v_ref_range_mps: [0 15]", "v_ref_rate_limit_mps2: 2.0", ...
        "safety: hold_max_s=0.5 clear_max_s=1.5 hard_flags=[1 2 3 4 6 7]", ...
        "controller: Kp=0.06 Ki=0.02 pitch_cmd_max=0.40 pitch_rate_max=0.25 integ_max=0.15", ...
