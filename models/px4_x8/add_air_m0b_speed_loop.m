    fprintf('functional check: ve_x tail mean %.3f m/s, theta tail %.4f rad\n', ...
        vexTail, thetaTail);
    set_param(loopEnable, 'Value', '0');
    set_param(model, 'SimulationCommand', 'update');
    save_system(model);

    % ---------- scenario config archive ----------
    stamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
    cfgDir = fullfile(wsRoot, 'results', 'm0b_config', stamp);
    if ~exist(cfgDir, 'dir')
