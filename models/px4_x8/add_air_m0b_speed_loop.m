        "flag5: |v - v_ref(unit-delayed)| > 1.0 m/s", ...
        "m0b_log_bus(7): [v_ref, pitch_cmd, v_err, optimizer_status, speed_loop_enable, ve_x, v]"};
    writelines(string(cfgLines), fullfile(cfgDir, 'm0b_config.txt'));

    result = struct( ...
        'model', model, ...
        'selectorBlock', string(selBlock), ...
        'controllerBlock', string(ctrlBlock), ...
        'busVariable', "m0b_log_bus", ...
        'configDir', string(cfgDir));
    fprintf('M0-B speed loop PASS: %s\n', model);
    fprintf('Defaults: speed_loop_enable=0 optimizer_enable=0 (baseline passthrough)\n');
    fprintf('Logged: m0b_log_bus (7)\n');
