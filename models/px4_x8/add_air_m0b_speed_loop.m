    add_block('simulink/Logic and Bit Operations/Relational Operator', ...
        [ov '/Theta Cmp'], 'Position', [260, 95, 300, 125], 'Operator', '>');
    add_block('simulink/Logic and Bit Operations/Logical Operator', ...
        [ov '/Att Flag OR'], 'Position', [340, 70, 370, 105], ...
        'Operator', 'OR', 'Inputs', '2');
    add_block('simulink/Signal Attributes/Data Type Conversion', ...
        [ov '/Att Flag Dbl'], 'Position', [390, 75, 430, 100], ...
        'OutDataTypeStr', 'double');
    add_block('built-in/Inport', [ov '/att_tol_in'], ...
        'Position', [30, 183, 60, 197], 'Port', '5');
    % bit 5: |v - v_ref| > speed_tol
    add_block('simulink/Math Operations/Sum', [ov '/Speed Diff'], ...
        'Position', [120, 160, 150, 190], 'Inputs', '+-');
    add_block('simulink/Math Operations/Abs', [ov '/Speed Abs'], ...
        'Position', [180, 165, 210, 185]);
    add_block('simulink/Logic and Bit Operations/Relational Operator', ...
        [ov '/Speed Cmp'], 'Position', [260, 160, 300, 190], 'Operator', '>');
    add_block('simulink/Signal Attributes/Data Type Conversion', ...
        [ov '/Speed Flag Dbl'], 'Position', [340, 165, 380, 185], ...
        'OutDataTypeStr', 'double');
    add_block('built-in/Inport', [ov '/speed_tol_in'], ...
        'Position', [30, 228, 60, 242], 'Port', '6');
    % assembly: pass through bits 1,2,4,6,7,8 and replace 3,5
    add_block('simulink/Signal Routing/Demux', [ov '/Flags Demux'], ...
        'Position', [120, 260, 125, 360], 'Outputs', '8');
    add_block('simulink/Signal Routing/Mux', [ov '/Flags Mux'], ...
        'Position', [420, 250, 425, 360], 'Inputs', '8');

    ovPorts = get_param(ov, 'PortHandles');
    attDemuxP = get_param([ov '/Att Demux'], 'PortHandles');
    phiAbsP = get_param([ov '/Phi Abs'], 'PortHandles');
    thAbsP = get_param([ov '/Theta Abs'], 'PortHandles');
    phiCmpP = get_param([ov '/Phi Cmp'], 'PortHandles');
    thCmpP = get_param([ov '/Theta Cmp'], 'PortHandles');
    orP = get_param([ov '/Att Flag OR'], 'PortHandles');
    orDblP = get_param([ov '/Att Flag Dbl'], 'PortHandles');
    spDiffP = get_param([ov '/Speed Diff'], 'PortHandles');
    spAbsP = get_param([ov '/Speed Abs'], 'PortHandles');
    spCmpP = get_param([ov '/Speed Cmp'], 'PortHandles');
    spDblP = get_param([ov '/Speed Flag Dbl'], 'PortHandles');
    fdP = get_param([ov '/Flags Demux'], 'PortHandles');
    fmP = get_param([ov '/Flags Mux'], 'PortHandles');

    add_line(ov, get_param([ov '/att'], 'PortHandles').Outport(1), ...
        attDemuxP.Inport(1), 'autorouting', 'on');
    add_line(ov, attDemuxP.Outport(1), phiAbsP.Inport(1), 'autorouting', 'on');
    add_line(ov, attDemuxP.Outport(2), thAbsP.Inport(1), 'autorouting', 'on');
    add_line(ov, phiAbsP.Outport(1), phiCmpP.Inport(1), 'autorouting', 'on');
    add_line(ov, thAbsP.Outport(1), thCmpP.Inport(1), 'autorouting', 'on');
    add_line(ov, get_param([ov '/att_tol_in'], 'PortHandles').Outport(1), ...
        phiCmpP.Inport(2), 'autorouting', 'on');
    add_line(ov, get_param([ov '/att_tol_in'], 'PortHandles').Outport(1), ...
        thCmpP.Inport(2), 'autorouting', 'on');
    add_line(ov, phiCmpP.Outport(1), orP.Inport(1), 'autorouting', 'on');
    add_line(ov, thCmpP.Outport(1), orP.Inport(2), 'autorouting', 'on');
    add_line(ov, orP.Outport(1), orDblP.Inport(1), 'autorouting', 'on');
    add_line(ov, get_param([ov '/v'], 'PortHandles').Outport(1), ...
        spDiffP.Inport(1), 'autorouting', 'on');
    add_line(ov, get_param([ov '/v_ref'], 'PortHandles').Outport(1), ...
        spDiffP.Inport(2), 'autorouting', 'on');
    add_line(ov, spDiffP.Outport(1), spAbsP.Inport(1), 'autorouting', 'on');
    add_line(ov, spAbsP.Outport(1), spCmpP.Inport(1), 'autorouting', 'on');
    add_line(ov, get_param([ov '/speed_tol_in'], 'PortHandles').Outport(1), ...
        spCmpP.Inport(2), 'autorouting', 'on');
    add_line(ov, spCmpP.Outport(1), spDblP.Inport(1), 'autorouting', 'on');
    add_line(ov, get_param([ov '/flags_raw'], 'PortHandles').Outport(1), ...
        fdP.Inport(1), 'autorouting', 'on');
    muxFeeds = {fdP.Outport(1), fdP.Outport(2), orDblP.Outport(1), ...
        fdP.Outport(4), spDblP.Outport(1), fdP.Outport(6), ...
        fdP.Outport(7), fdP.Outport(8)};
    for k = 1:8
        add_line(ov, muxFeeds{k}, fmP.Inport(k), 'autorouting', 'on');
    end
    add_line(ov, fmP.Outport(1), ...
        get_param([ov '/flags_out'], 'PortHandles').Inport(1), ...
        'autorouting', 'on');
    add_block('simulink/Sinks/Terminator', [ov '/Term Bit3'], ...
        'Position', [180, 300, 210, 315]);
    add_block('simulink/Sinks/Terminator', [ov '/Term Bit5'], ...
        'Position', [180, 330, 210, 345]);
    add_line(ov, fdP.Outport(3), ...
        get_param([ov '/Term Bit3'], 'PortHandles').Inport(1), 'autorouting', 'on');
    add_line(ov, fdP.Outport(5), ...
        get_param([ov '/Term Bit5'], 'PortHandles').Inport(1), 'autorouting', 'on');

    % root sources for the override subsystem
    spTolConst = [model '/M0B Speed Tol'];
    add_block('simulink/Sources/Constant', spTolConst, ...
        'Position', [x0 + 500, y1 - 120, x0 + 530, y1 - 90], 'Value', '1.0');
    attObsRootPort = get_param(acWrapper, 'PortHandles').Outport(3);
    add_line(model, get_param(flagsBlock, 'PortHandles').Outport(1), ...
        ovPorts.Inport(1), 'autorouting', 'on');       % flags_raw
    add_line(model, attObsRootPort, ovPorts.Inport(2), ...
        'autorouting', 'on');                          % att (6)
    add_line(model, get_param(vZoh, 'PortHandles').Outport(1), ...
        ovPorts.Inport(3), 'autorouting', 'on');       % v (1 ms)
    add_line(model, get_param(refDelay, 'PortHandles').Outport(1), ...
        ovPorts.Inport(4), 'autorouting', 'on');       % v_ref delayed
    add_line(model, get_param(attTolConst, 'PortHandles').Outport(1), ...
        ovPorts.Inport(5), 'autorouting', 'on');       % att_tol
    add_line(model, get_param(spTolConst, 'PortHandles').Outport(1), ...
        ovPorts.Inport(6), 'autorouting', 'on');       % speed_tol


    % ---------- 7. m0b log bus ----------
    add_block('simulink/Signal Routing/Mux', busMux, ...
        'Inputs', '7', 'Position', [x0 + 680, y1 + 100, x0 + 690, y1 + 220]);
    busPorts = get_param(busMux, 'PortHandles');
    add_line(model, selPorts.Outport(1), busPorts.Inport(1), ...
        'autorouting', 'on');                                     % v_ref
    add_line(model, ctlPorts.Outport(1), busPorts.Inport(2), ...
        'autorouting', 'on');                                     % pitch_cmd
    add_line(model, ctlPorts.Outport(2), busPorts.Inport(3), ...
        'autorouting', 'on');                                     % v_err
    add_line(model, selPorts.Outport(2), busPorts.Inport(4), ...
        'autorouting', 'on');                                     % status
    add_line(model, get_param(loopEnable, 'PortHandles').Outport(1), ...
        busPorts.Inport(5), 'autorouting', 'on');                 % enable
    add_line(model, get_param(vexZoh, 'PortHandles').Outport(1), ...
        busPorts.Inport(6), 'autorouting', 'on');                 % ve_x
